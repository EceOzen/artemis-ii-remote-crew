# --- Constants ---
GM = 3.986004418e14      # Earth's gravitational parameter [m³/s²]
R_earth = 6_371_000      # Earth's mean radius [m]

# --- Artemis II mission parameters ---
h_parking  = 185_000     # Parking orbit altitude [m]  (approx. Artemis II)
h_moon     = 384_400_000 # Mean Earth–Moon distance [m]

# --- Derived radii (from Earth's center) ---
r_parking = R_earth + h_parking
r_moon    = h_moon          # already center-to-center approx.

print(f"Parking orbit radius : {r_parking/1e6:.4f} × 10⁶ m")
print(f"Moon distance        : {r_moon/1e6:.1f} × 10⁶ m")

# ============================================================
# Cell 2 — Vis-viva: velocities & Δv
# ============================================================

# --- 1. Circular velocity in parking orbit ---
v_circular = np.sqrt(GM / r_parking)

# --- 2. Transfer ellipse semi-major axis ---
# Perigee = parking orbit, Apogee = Moon distance
a_transfer = (r_parking + r_moon) / 2

# --- 3. TLI velocity (vis-viva at perigee of transfer ellipse) ---
v_tli = np.sqrt(GM * (2/r_parking - 1/a_transfer))

# --- 4. Δv required ---
delta_v = v_tli - v_circular

# --- Print results ---
print("=" * 45)
print("       ARTEMIS II — TLI Δv BUDGET")
print("=" * 45)
print(f"  Parking orbit velocity  : {v_circular:.2f} m/s")
print(f"  TLI injection velocity  : {v_tli:.2f} m/s")
print(f"  Transfer orbit a        : {a_transfer/1e6:.2f} × 10⁶ m")
print(f"  Δv required             : {delta_v:.2f} m/s")
print(f"  Δv in km/s              : {delta_v/1000:.4f} km/s")
print("=" * 45)

