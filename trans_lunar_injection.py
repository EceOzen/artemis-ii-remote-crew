trail_x, trail_y = [], []

def init():
    spacecraft.set_data([], [])
    trail.set_data([], [])
    engine_glow.set_markersize(0)
    phase_text.set_text('')
    vel_text.set_text('')
    dv_bar.set_width(0)
    trail_x.clear()
    trail_y.clear()
    return spacecraft, trail, engine_glow, phase_text, vel_text, dv_bar

def update(frame):
    trail_x.clear()
    trail_y.clear()

    if frame < N_orbit:
        # Phase 1: parking orbit
        angle = orbit_angles[frame]
        x = 1.1 * np.cos(angle)
        y = 1.1 * np.sin(angle)
        # trail: last 20 frames
        start = max(0, frame - 20)
        for f in range(start, frame + 1):
            a = orbit_angles[f]
            trail_x.append(1.1 * np.cos(a))
            trail_y.append(1.1 * np.sin(a))

        spacecraft.set_data([x], [y])
        spacecraft.set_color('#10B981')
        trail.set_color('#10B981')
        engine_glow.set_markersize(0)
        phase_text.set_text('Phase 1: parking orbit')
        vel_text.set_text('v = 7,797 m/s')
        dv_bar.set_width(0)

    elif frame < N_orbit + N_burn:
        # Phase 2: burn!
        t = (frame - N_orbit) / N_burn
        x = 1.1
        y = (1 - t) * 0.0
        # interpolate velocity display
        v_current = v_circular + t * delta_v
        dv_current = t * delta_v

        spacecraft.set_data([x], [y])
        spacecraft.set_color('#F59E0B')
        trail.set_data([], [])
        # engine glow pulses
        glow_size = 12 + 8 * np.sin(frame * 0.8)
        engine_glow.set_data([x - 0.15], [y])
        engine_glow.set_markersize(glow_size)
        phase_text.set_text('Phase 2: TLI BURN FIRING')
        phase_text.set_color('#F59E0B')
        vel_text.set_text(f'v = {v_current:,.0f} m/s')
        dv_bar.set_width(dv_current)

    else:
        # Phase 3: escape arc
        i = frame - N_orbit - N_burn
        x = x_escape[i]
        y = y_escape[i]
        # trail: last 15 frames of escape
        start = max(0, i - 15)
        for j in range(start, i + 1):
            trail_x.append(x_escape[j])
            trail_y.append(y_escape[j])

        spacecraft.set_data([x], [y])
        spacecraft.set_color('#F59E0B')
        trail.set_color('#F59E0B')
        engine_glow.set_markersize(0)
        phase_text.set_text('Phase 3: trans-lunar trajectory')
        phase_text.set_color('#94A3B8')
        vel_text.set_text(f'v = {v_tli:,.0f} m/s  →  Moon')
        dv_bar.set_width(delta_v)

    trail.set_data(trail_x, trail_y)
    return spacecraft, trail, engine_glow, phase_text, vel_text, dv_bar

