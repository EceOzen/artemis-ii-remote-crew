# ── physics helpers ──────────────────────────────────────────
GM_earth = 3.986004418e14
GM_moon  = 4.902800066e12
R_earth  = 6_371_000
R_moon   = 1_737_400
D_moon   = 384_400_000   # Earth-Moon distance

# ── build free-return trajectory (patched conic approx.) ────
# Outbound: half of transfer ellipse (Earth → Moon)
# Flyby:    hyperbolic arc around Moon
# Return:   mirror leg back to Earth

def transfer_ellipse(n=300):
    """Outbound leg — half ellipse from LEO to Moon distance."""
    a = (R_earth + 185_000 + D_moon) / 2
    e = 1 - (R_earth + 185_000) / a
    theta = np.linspace(0, np.pi, n)
    r = a * (1 - e**2) / (1 + e * np.cos(theta))
    # scale to plot units (D_moon = 1.0)
    scale = 1.0 / D_moon
    x = r * np.cos(theta) * scale
    y = r * np.sin(theta) * scale
    return x, y

def lunar_flyby(moon_x, moon_y, n=80):
    """Hyperbolic arc around the Moon."""
    angles = np.linspace(np.pi * 0.55, np.pi * 1.45, n)
    r_flyby = 0.06   # plot units
    x = moon_x + r_flyby * np.cos(angles)
    y = moon_y + r_flyby * np.sin(angles)
    return x, y

def return_leg(end_x, end_y, n=250):
    """Return arc — mirror of outbound, angled back to Earth."""
    t = np.linspace(0, 1, n)
    # cubic bezier control points for natural return curve
    p0 = np.array([end_x, end_y])
    p1 = np.array([end_x * 0.6, end_y * 1.3])
    p2 = np.array([-0.3, 0.4])
    p3 = np.array([0.0, 0.0])   # Earth
    x = ((1-t)**3*p0[0] + 3*(1-t)**2*t*p1[0] +
         3*(1-t)*t**2*p2[0] + t**3*p3[0])
    y = ((1-t)**3*p0[1] + 3*(1-t)**2*t*p1[1] +
         3*(1-t)*t**2*p2[1] + t**3*p3[1])
    return x, y

