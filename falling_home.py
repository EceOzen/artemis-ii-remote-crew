# ── Atmospheric density model ─────────────────────────────────
def rho_atm(h):
    """Exponential atmosphere density kg/m³."""
    return RHO_0 * np.exp(-h / H_SCALE)

# ── Stagnation point heat flux (Sutton-Graves) ────────────────
def q_stag(v_ms, h_m, R_nose=2.0):
    """
    Stagnation heat flux W/m²
    Sutton-Graves approximation
    R_nose: nose radius [m]
    """
    rho  = rho_atm(h_m)
    k_sg = 1.742e-4   # Sutton-Graves constant
    return k_sg * np.sqrt(rho / R_nose) * v_ms**3

# ── Drag deceleration ─────────────────────────────────────────
def drag_decel(v_ms, h_m):
    """Drag deceleration m/s²."""
    rho = rho_atm(h_m)
    return 0.5 * rho * v_ms**2 * \
           ORION_CD * ORION_AREA / ORION_MASS

