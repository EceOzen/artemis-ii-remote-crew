# ── numerical trajectory integration ─────────────────────────
def integrate_trajectory(
        gamma_deg, v0=V_ENTRY_MS,
        h0=H_ENTRY, dt=0.1,
        skip=True):
    """
    2D trajectory integration.
    gamma_deg : entry angle (negative = down)
    skip      : apply skip manoeuvre
    Returns (t, h, v, range_km, g_load, q)
    """
    gamma = np.radians(gamma_deg)
    v     = v0
    h     = float(h0)
    x     = 0.0      # downrange [m]
    t     = 0.0

    t_arr, h_arr  = [t], [h]
    v_arr, x_arr  = [v], [x]
    g_arr, q_arr  = [0.0], [0.0]

    skipped = False

    while h > 0 and t < 900:
        rho  = rho_atm(h)
        q_d  = 0.5 * rho * v**2
        drag = q_d * ORION_CD * \
               ORION_AREA / ORION_MASS
        grav = G_ACCEL * \
               (R_EARTH / (R_EARTH + h))**2

        # lift (blunt body has small L/D)
        ld   = 0.18   # lift-to-drag ratio
        lift = drag * ld

        # equations of motion
        # along-path deceleration
        dv   = -(drag + grav *
                 np.sin(-gamma))
        # path angle rate
        if v > 10:
            dgamma = (lift / v -
                      grav * np.cos(-gamma) / v +
                      v / (R_EARTH + h)) * \
                     (1 / v)
        else:
            dgamma = 0

        # skip manoeuvre —
        # at ~55 km pitch up momentarily
        if skip and h < 60_000 and \
           h > 45_000 and not skipped:
            gamma = gamma - \
                    np.radians(3.0)
            skipped = True

        gamma += dgamma * dt
        v     = max(v + dv * dt, 5)
        h     = h + v * np.sin(gamma) * dt
        x    += v * np.cos(-gamma) * dt
        t    += dt

        g_l  = drag / G_ACCEL
        q_s  = q_stag(v, max(h, 1000))

        t_arr.append(t)
        h_arr.append(max(h, 0))
        v_arr.append(v)
        x_arr.append(x)
        g_arr.append(g_l)
        q_arr.append(q_s)

        if h <= 0:
            break

    return (np.array(t_arr) / 60,
            np.array(h_arr) / 1000,
            np.array(v_arr),
            np.array(x_arr) / 1000,
            np.array(g_arr),
            np.array(q_arr) / 1e6)

