def free_return_arc(
        max_dist_norm, close_norm,
        n_pts=500, y_offset=0.0,
        outbound_spread=0.18):
    """
    Generate a figure-8 free-return arc
    in normalised Earth-Moon units.
    max_dist_norm : max distance / D_moon
    close_norm    : closest Moon / D_moon
    y_offset      : vertical shift
    """
    t = np.linspace(0, 2*np.pi, n_pts)

    # outbound leg — Earth to Moon
    # parametric arc approaching Moon
    # from below (typical free-return geometry)
    t_out = np.linspace(0, np.pi, n_pts//2)

    # outbound: rises from Earth, arcs to Moon
    x_out = (MOON_X * np.sin(t_out/2)**0.7 +
             outbound_spread *
             np.sin(t_out) * 0.5)
    y_out = (outbound_spread *
             np.sin(t_out) + y_offset)

    # lunar flyby arc — loop around Moon
    # radius = closest approach
    t_fly = np.linspace(
        -np.pi * 0.6,
         np.pi * 0.6, n_pts//4)
    r_fly  = close_norm + \
             0.02 * (1 - np.cos(t_fly))
    x_fly  = MOON_X + \
             r_fly * np.cos(t_fly + np.pi)
    y_fly  = r_fly * np.sin(t_fly + np.pi) + \
             y_offset

    # return leg — Moon back to Earth
    # mirror of outbound with slight shift
    x_ret = x_out[::-1] * 0.98
    y_ret = -y_out[::-1] * 0.95

    return (np.concatenate([x_out, x_fly, x_ret]),
            np.concatenate([y_out, y_fly, y_ret]))

