# ── Trajectory builder ────────────────────────────────────────
def build_trajectory(
        t_launch, t_tli, t_flyby,
        t_splash, max_km, close_km,
        n_pts=3000):
    t_total = met_hours(t_splash, t_launch)
    t_tli_h = met_hours(t_tli,    t_launch)
    t_fly_h = met_hours(t_flyby,  t_launch)
    t_max_h = t_fly_h + 0.08

    t = np.linspace(0, t_total, n_pts)
    d = np.zeros_like(t)

    for i, ti in enumerate(t):
        if ti < t_tli_h:
            d[i] = 185
        elif ti < t_fly_h:
            frac  = (ti - t_tli_h) / \
                    (t_fly_h - t_tli_h)
            ease  = 3*frac**2 - 2*frac**3
            d[i]  = 185 + (max_km - 185) * ease
        elif ti < t_max_h:
            frac  = (ti - t_fly_h) / \
                    (t_max_h - t_fly_h)
            d[i]  = max_km - \
                    (max_km - close_km) * \
                    np.sin(frac * np.pi * 0.5)
        else:
            frac  = (ti - t_max_h) / \
                    (t_total - t_max_h)
            ease  = frac**1.8
            d[i]  = max_km * (1 - ease) + \
                    185 * ease
    return t, d

