# Units: normalized to Earth-Moon distance = 1
# Earth at (-mu, 0), Moon at (1-mu, 0)
# mu = M_moon / (M_earth + M_moon)

mu    = M_moon / (M_earth + M_moon)   # ~0.01215
omega = np.sqrt(GM_earth / D_moon**3)

# grid in normalized units
N     = 600
xlim  = 1.4
