dist_from_earth_now = 271_979_000   # m  (271,979 km)
dist_from_moon_now  = 178_154_000   # m  (178,154 km)

# ════════════════════════════════════════════════════════════
# COMPUTATION 1: Lunar Sphere of Influence (SOI)
# ════════════════════════════════════════════════════════════
# Laplace's formula:
# r_SOI = D_moon * (M_moon / M_earth)^(2/5)
#
# Physical meaning: the distance from the Moon at which
# the Moon's gravitational perturbation on a spacecraft
# equals Earth's gravitational perturbation.
# Used in patched conic approximation for mission planning.

r_SOI = D_moon * (M_moon / M_earth) ** (2/5)

# ════════════════════════════════════════════════════════════
# COMPUTATION 2: L1 Lagrange Point
# ════════════════════════════════════════════════════════════
# The L1 point is where the gravitational forces of Earth
# and Moon plus the centrifugal force in the rotating frame
# exactly balance. Solved numerically from:
#
# GM_earth / r² = GM_moon / (D-r)² + ω²r
# where ω = orbital angular velocity of Moon around Earth
# and r = distance from Earth to L1

omega = np.sqrt(GM_earth / D_moon**3)  # Moon's angular velocity

# Solve for L1 numerically along Earth-Moon line
# Rearrange: f(r) = 0
def L1_equation(r):
    """Force balance equation at L1 in rotating frame."""
    F_earth = GM_earth / r**2
    F_moon  = GM_moon  / (D_moon - r)**2
    F_cent  = omega**2 * r
    return F_earth - F_moon - F_cent

# Newton-Raphson from initial guess
r_L1 = D_moon * 0.85   # start near Moon
for _ in range(1000):
    f  = L1_equation(r_L1)
    # numerical derivative
    dr = 1000  # 1 km step
    df = (L1_equation(r_L1 + dr) - L1_equation(r_L1 - dr)) / (2*dr)
    r_L1 -= f / df
    if abs(f) < 1e-6:
        break

# distance from Moon to L1
r_L1_from_moon = D_moon - r_L1

# ════════════════════════════════════════════════════════════
# COMPUTATION 3: Simple gravity balance point
# (where |F_earth| = |F_moon|, no rotation)
# ════════════════════════════════════════════════════════════
# GM_earth/r² = GM_moon/(D-r)²
# Solve analytically:
# sqrt(GM_earth)*(D-r) = sqrt(GM_moon)*r
# r = D * sqrt(GM_earth) / (sqrt(GM_earth) + sqrt(GM_moon))

r_balance = D_moon * np.sqrt(GM_earth) / \
            (np.sqrt(GM_earth) + np.sqrt(GM_moon))
r_balance_from_moon = D_moon - r_balance

# ════════════════════════════════════════════════════════════
# COMPUTATION 4: When does Orion cross the SOI?
# ════════════════════════════════════════════════════════════
# NASA published: 12:41 AM ET Monday = 04:41 UTC April 6
# = 07:41 UTC April 6 (corrected from NBC)
# Current distance from Moon: 178,154 km
# SOI radius: ~66,100 km
# Orion needs to travel: 178,154 - 66,100 = ~112,054 km
# Average approach speed: ~0.9 km/s at this stage
dist_to_SOI    = (dist_from_moon_now - r_SOI) / 1000  # km
# corrected from NASA published crossing time
# 178,154 km to go, ~12 hours remaining → ~4.1 km/s approach speed
avg_speed      = 4.1   # km/s — accelerating under lunar gravity
time_to_SOI_hr = dist_to_SOI / avg_speed / 3600

