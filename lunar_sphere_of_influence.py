def get_position(p):
    """Get (x_norm, y_norm) along trajectory."""
    p = np.clip(p, 0, 1)
    x = p
    y = 0.12 * np.sin(np.pi * p)
    return x, y

def get_distances(p):
    """Get distance from Earth and Moon in meters."""
    p  = np.clip(p, 0, 1)
    x  = p * D_moon
    de = x                      # from Earth
    dm = D_moon - x             # from Moon
    return max(de, 1e6), max(dm, 1e6)

def get_gravity_ratio(p):
    de, dm = get_distances(p)
    g_e = GM_earth / de**2
    g_m = GM_moon  / dm**2
    return g_m / g_e, g_e, g_m

def init():
    orion_dot.set_data([], [])
    ratio_line.set_data([], [])
    ratio_dot.set_data([], [])
    phase_text.set_text('')
    crossed_soi.set_text('')
