SOI_UTC     = datetime(2026, 4, 6,   4, 41, tzinfo=timezone.utc)
FLYBY_UTC   = datetime(2026, 4, 6,  18, 45, tzinfo=timezone.utc)
MAXDIST_UTC = datetime(2026, 4, 6,  23,  5, tzinfo=timezone.utc)
NOW_UTC     = datetime.now(timezone.utc)

def met(dt):
    """Mission elapsed time in hours."""
    return (dt - LAUNCH_UTC).total_seconds() / 3600

MET_TLI     = met(TLI_UTC)
MET_SOI     = met(SOI_UTC)
MET_FLYBY   = met(FLYBY_UTC)
MET_MAXDIST = met(MAXDIST_UTC)
MET_NOW     = met(NOW_UTC)

# ── build distance profile (from Moon) ───────────────────────
t_hours = np.linspace(MET_TLI, MET_FLYBY + 10, 5000)

def dist_from_moon(t):
    """Distance from Moon center [km] as function of MET [hours]."""
    d = np.zeros_like(t)
    for i, ti in enumerate(t):
        if ti < MET_TLI:
            d[i] = D_moon/1000 - 185   # parking orbit
        elif ti < MET_SOI:
            # outbound coast — approaching Moon
            frac  = (ti - MET_TLI) / (MET_SOI - MET_TLI)
            ease  = 3*frac**2 - 2*frac**3  # cubic ease-in
            d[i]  = (D_moon/1000 - 185) - \
                    ((D_moon/1000 - 185) - r_SOI/1000) * ease
        elif ti < MET_FLYBY:
            # inside SOI — falling toward Moon
            frac  = (ti - MET_SOI) / (MET_FLYBY - MET_SOI)
            ease  = 3*frac**2 - 2*frac**3
            d[i]  = r_SOI/1000 - \
                    (r_SOI/1000 - 4066*1.609) * ease
        else:
            # post flyby — receding
            frac  = (ti - MET_FLYBY) / 10
            d[i]  = 4066*1.609 + frac * 50000
    return d

