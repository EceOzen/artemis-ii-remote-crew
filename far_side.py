# Laplacian of Gaussian finds circular dark blobs
# (crater interiors are darker than surroundings)
# Works by convolving image with LoG at multiple scales

# normalize to float [0,1] for blob_log
img_float = img_eq.astype(np.float32) / 255.0

# invert — blob_log detects DARK blobs on bright background
# crater interiors are dark → invert so they become bright
img_inv = 1.0 - img_float

blobs = blob_log(
    img_inv,
    min_sigma=3,      # min crater radius ~3px → ~0.3km
    max_sigma=35,     # max crater radius ~35px → ~3.5km
    num_sigma=20,     # number of scale steps
    threshold=0.04,   # detection sensitivity
    overlap=0.4       # allow 40% overlap between blobs
)

# blob_log returns (y, x, sigma) — convert sigma to radius
# radius = sigma * sqrt(2)
blobs_r = blobs.copy()
blobs_r[:, 2] = blobs_r[:, 2] * np.sqrt(2)

print(f"LoG blobs detected  : {len(blobs_r)}")

# ── Feature extraction per blob ───────────────────────────────
# For each detected crater, extract:
# 1. Mean intensity inside crater (interior darkness)
# 2. Mean intensity in rim annulus (rim brightness)
# 3. Contrast ratio = rim / interior
# 4. Circularity score from Hough result

features_list = []
for blob in blobs_r:
    y, x, r = int(blob[0]), int(blob[1]), max(int(blob[2]), 3)

    # create masks
    Y, X = np.ogrid[:512, :512]
    dist = np.sqrt((X - x)**2 + (Y - y)**2)

    mask_interior = dist < r * 0.7
    mask_rim      = (dist >= r * 0.8) & (dist < r * 1.3)

    if mask_interior.sum() == 0 or mask_rim.sum() == 0:
        continue

    interior_mean = img_eq[mask_interior].mean()
    rim_mean      = img_eq[mask_rim].mean()
    contrast      = rim_mean / (interior_mean + 1e-6)
    rim_std       = img_eq[mask_rim].std()

    features_list.append({
        'y': y, 'x': x, 'r': r,
        'interior': interior_mean,
        'rim':      rim_mean,
        'contrast': contrast,
        'rim_std':  rim_std,
    })

features_arr = np.array([
    [f['contrast'], f['rim_std'],
     f['r'],        f['interior']]
    for f in features_list
])

print(f"Features extracted  : {len(features_list)}")

# ── Simple scoring — rank by crater likelihood ────────────────
# Good craters have:
#   high contrast (bright rim, dark interior)
#   moderate rim_std (textured rim, not flat)
#   radius in geologically common range

def crater_score(f):
    contrast_score = min(f['contrast'] / 1.5, 1.0)
    texture_score  = min(f['rim_std'] / 20.0, 1.0)
    size_score     = 1.0 - abs(f['r'] - 20) / 40
    size_score     = max(size_score, 0.1)
    return (0.5 * contrast_score +
            0.3 * texture_score +
            0.2 * size_score)

scores = np.array([crater_score(f) for f in features_list])

# tier by score
if len(scores) > 0:
    t_high = np.percentile(scores, 70)
    t_med  = np.percentile(scores, 35)
