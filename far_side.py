# CLAHE via OpenCV — more control than skimage version
clahe   = cv2.createCLAHE(clipLimit=2.0,
                           tileGridSize=(8, 8))
img_eq  = clahe.apply(img_raw)   # still uint8

# ── edge detection — work in uint8 throughout ─────────────────
# Gaussian blur in OpenCV keeps uint8
img_blur = cv2.GaussianBlur(img_eq, (5, 5), 1.5)

# Canny in OpenCV — thresholds in 0-255 range
edges_cv = cv2.Canny(img_blur,
                     threshold1=20,
                     threshold2=60)

print(f"Image dtype     : {img_raw.dtype}")
print(f"Image range     : {img_raw.min()}–{img_raw.max()}")
print(f"Blur range      : {img_blur.min()}–{img_blur.max()}")
print(f"Edge pixels     : {edges_cv.sum() // 255}")

# ── Hough Circle Transform ────────────────────────────────────
# edges_cv is 0/255 uint8 — convert to bool for skimage
edges_bool = edges_cv > 0
print(f"Edge bool pixels: {edges_bool.sum()}")

radii     = np.arange(8, 70, 2)
hough_res = hough_circle(edges_bool, radii)

print(f"Hough max       : {hough_res.max():.4f}")
print(f"Hough 99th pct  : {np.percentile(hough_res,99):.4f}")
print(f"Hough 99.9th pct: {np.percentile(hough_res,99.9):.4f}")

