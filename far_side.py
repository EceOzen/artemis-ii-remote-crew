fig.patch.set_facecolor('#0D1117')

# ── Step 1: Preprocessing ─────────────────────────────────────
# Gaussian blur to reduce noise before edge detection
sigma     = 2.0
img_blur  = gaussian(img_eq, sigma=sigma)

# ── Step 2: Edge detection (Canny) ───────────────────────────
# Canny finds crater rims as circular edge features
# low_threshold, high_threshold control edge sensitivity
edges = canny(img_blur,
              sigma=1.5,
              low_threshold=5,
              high_threshold=15)

# ── Step 3: Hough Circle Transform ───────────────────────────
# Test a range of radii — craters from 10 to 80 pixels
# At LRO WAC resolution (~100m/px), this covers
# craters from ~1 km to ~8 km diameter
radii = np.arange(10, 80, 2)
hough_res = hough_circle(edges, radii)

# Extract top crater candidates
accums, cx, cy, radii_detected = hough_circle_peaks(
    hough_res, radii,
    min_xdistance=15,
    min_ydistance=15,
    total_num_peaks=40,
    threshold=0.25
)

# safety check
if len(accums) == 0:
    print("No detections at 0.25 — trying lower threshold")
    accums, cx, cy, radii_detected = hough_circle_peaks(
        hough_res, radii,
        min_xdistance=10,
        min_ydistance=10,
        total_num_peaks=40,
        threshold=0.15
    )

print(f"Detections found: {len(accums)}")

# ── Step 4: Filter by accumulator strength ────────────────────
# Higher accumulator = more confident detection
threshold_high = np.percentile(accums, 60)
threshold_med  = np.percentile(accums, 30)

high_conf = accums >= threshold_high
med_conf  = (accums >= threshold_med) & ~high_conf
low_conf  = accums < threshold_med

